/**
 * batt_hal.h — 电池电量检测硬件抽象层
 * 通过 ADC 电压分压读取锂电池电压，更新电量状态
 *
 * 硬件接线:
 *   Vbat(+) ── R1(100k) ──┬── GPIO0(ADC) ── R2(100k) ── GND
 *   V_adc = Vbat * R2/(R1+R2) = Vbat / 2
 */

#ifndef BATT_HAL_H
#define BATT_HAL_H

#include "../config.h"

// ================================================================
//  初始化
// ================================================================

/** 初始化电池 ADC 引脚和衰减 */
void battInit();

// ================================================================
//  读取与更新
// ================================================================

/** 读取 ADC，计算电池电压，更新 currentBatt 状态 */
void updateBattery();

/** 获取最近一次电池电压 (mV) */
int getBatteryVoltage();

/** 获取电池百分比 (0-100) */
int getBatteryPercent();

#endif // BATT_HAL_H
