/**
 * button_hal.h — 5 键直连 GPIO 按键硬件抽象层
 * 负责 GPIO 读取、去抖、边沿检测、长按/双击事件生成
 *
 * 按键接线 (per README.md):
 *   GPIO4 ─┬─ 按键A ─ GND    上/下翻页 (方向键)
 *   GPIO3 ─┬─ 按键B ─ GND    返回/暂停
 *   GPIO2 ─┬─ 按键C ─ GND    短按→确认 / 长按→语音  ⚠️ Strapping 引脚
 *   GPIO1 ─┬─ 按键D ─ GND    短按→模式切换 / 长按→设置
 *   GPIO0 ─┬─ 按键E ─ GND    长按 2s → 开关机
 */

#ifndef BUTTON_HAL_H
#define BUTTON_HAL_H

#include "../config.h"

// ================================================================
//  初始化
// ================================================================

/** 初始化 5 键 GPIO 为 INPUT_PULLUP，初始化 buttons[] 等数组 */
void initButtons();

// ================================================================
//  扫描与读取
// ================================================================

/** 读取 5 键 GPIO，进行去抖和事件检测，更新 buttons[] 数组 */
void readButtons();

// ================================================================
//  调试输出
// ================================================================

/** 通过串口打印按键调试信息 (每 1s 一次) */
void debugPrintButtons();

#endif // BUTTON_HAL_H
